"""Generate backend and frontend field registry artifacts from the canonical YAML."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "config" / "candidates" / "field_registry.yaml"
BACKEND = ROOT.parent / "backend-api" / "internal" / "document" / "field_registry_gen.go"
FRONTEND = ROOT.parent / "frontend" / "src" / "lib" / "field_registry.gen.ts"


def render() -> tuple[str, str]:
    raw = SOURCE.read_bytes()
    doc = yaml.safe_load(raw) or {}
    digest = hashlib.sha256(raw).hexdigest()
    header = f"Code generated by app/tools/sync_field_registry.py from config/candidates/field_registry.yaml (sha256 {digest}). DO NOT EDIT."
    entries = {kind: [(name, str(spec.get("cand_type", "text")), str(spec.get("cardinality", "one")), spec.get("cand_type") == "table")
                      for name, spec in fields.items() if isinstance(spec, dict)]
               for kind, fields in doc.items() if isinstance(fields, dict)}
    go = ["// " + header, "package document", "", "type FieldSpec struct { Name string; CandType string; Cardinality string; IsTable bool }", "", "var FieldRegistry = map[string][]FieldSpec{"]
    for kind, fields in entries.items():
        go.append(f'\t"{kind}": {{')
        go.extend(f'\t\t{{Name: "{name}", CandType: "{cand}", Cardinality: "{card}", IsTable: {str(table).lower()}}},' for name, cand, card, table in fields)
        go.append("\t},")
    go.extend(["}", ""])
    ts = [f"// {header}", 'export type DocumentType = "INVOICE" | "POD" | "RATE_AGREEMENT" | "SURAT_JALAN";',
          'export interface FieldSpec { name: string; cand_type: string; cardinality: string; is_table: boolean }',
          "export const FIELD_REGISTRY: Record<DocumentType, FieldSpec[]> = {"]
    for kind, fields in entries.items():
        ts.append(f'  {kind}: [')
        ts.extend(f'    {{ name: "{name}", cand_type: "{cand}", cardinality: "{card}", is_table: {str(table).lower()} }},' for name, cand, card, table in fields)
        ts.append("  ],")
    ts.extend(["};", ""])
    return "\n".join(go), "\n".join(ts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    go, ts = render()
    generated = ((BACKEND, go), (FRONTEND, ts))
    stale = []
    for path, text in generated:
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("Registry artifacts are stale: " + ", ".join(stale))
        return 1
    print("Field registry artifacts are synchronized.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
